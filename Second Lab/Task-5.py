# Create a dictionary with at least three key-value pairs
person_info = {
    'name': 'Ali',
    'age': 22,
    'city': 'Lahore'
}

# Print the entire dictionary
print("Original person_info:", person_info)

# Access and print the value of 'age'
print("Age:", person_info['age'])

# Update the value of 'city'
person_info['city'] = 'Karachi'

# Print the updated dictionary
print("Updated person_info:", person_info)