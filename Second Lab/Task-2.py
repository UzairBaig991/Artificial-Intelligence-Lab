# Multi-line string using triple quotes
my_string = """This is the first line.
This is the second line of the multi-line string."""

# Complex number literal
my_number = 3 + 4j

# Boolean literal
is_true = True

# Print value and type of each variable
print("my_string:", my_string)
print("Type of my_string:", type(my_string))

print("\nmy_number:", my_number)
print("Type of my_number:", type(my_number))

print("\nis_true:", is_true)
print("Type of is_true:", type(is_true))