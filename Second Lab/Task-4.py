# Create a list with at least four items
shopping_list = ['milk', 'bread', 'eggs', 'butter']

# Print the entire shopping list
print("Original shopping list:", shopping_list)

# Add one new item to the end
shopping_list.append('apple')

# Print the updated list
print("Updated shopping list:", shopping_list)

# Check if a specific item is in the list
if 'apple' in shopping_list:
    print("'apple' is present in the shopping list.")
else:
    print("'apple' is not present in the shopping list.")